void Gc9a01::sendCommand(uint8_t cmd, const uint8_t* args, uint8_t count) {
  csLow();
  dcCommand();
  spiSend(cmd);
  dcData();
  for (uint8_t i = 0; i < count; i++) spiSend(pgm_read_byte(args + i));
  csHigh();
}

void Gc9a01::begin(uint8_t rotation) {
  pinMode(pins::LCD_CS, OUTPUT);
  csHigh();
  pinMode(pins::LCD_DC, OUTPUT);
  dcData();
  SPI.begin();
  SPI.beginTransaction(SPISettings(DISPLAY_SPI_HZ, MSBFIRST, SPI_MODE0));   // kept open: the LCD is the only SPI device

  pinMode(pins::LCD_RST, OUTPUT);                  // hardware reset, same timing as the Adafruit library
  digitalWrite(pins::LCD_RST, HIGH);
  delay(100);
  digitalWrite(pins::LCD_RST, LOW);
  delay(100);
  digitalWrite(pins::LCD_RST, HIGH);
  delay(200);

  const uint8_t* p = kInit;
  uint8_t cmd;
  while ((cmd = pgm_read_byte(p++)) != 0) {
    uint8_t flags = pgm_read_byte(p++);
    uint8_t n = flags & 0x7F;
    sendCommand(cmd, p, n);
    p += n;
    if (flags & 0x80) delay(150);
  }

  uint8_t madctl = pgm_read_byte(&kMadctl[rotation & 3]);
  csLow();
  dcCommand();
  spiSend(CMD_MADCTL);
  dcData();
  spiSend(madctl);
  csHigh();
}

void Gc9a01::openWindow(int16_t x0, int16_t y0, int16_t x1, int16_t y1) {
  csLow();
  dcCommand();
  spiSend(CMD_CASET);
  dcData();
  spiSend16((uint16_t)x0);
  spiSend16((uint16_t)x1);
  dcCommand();
  spiSend(CMD_RASET);
  dcData();
  spiSend16((uint16_t)y0);
  spiSend16((uint16_t)y1);
  dcCommand();
  spiSend(CMD_RAMWR);
  dcData();
}

void Gc9a01::closeWindow() { csHigh(); }

void Gc9a01::streamColor(uint16_t color, uint32_t count) {
  uint8_t hi = (uint8_t)(color >> 8);
  uint8_t lo = (uint8_t)color;
  while (count--) {
    spiSend(hi);
    spiSend(lo);
  }
}

void Gc9a01::fillRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color) {
  if (w <= 0 || h <= 0) return;
  if (x < 0) { w = (int16_t)(w + x); x = 0; }
  if (y < 0) { h = (int16_t)(h + y); y = 0; }
  if (x >= kSize || y >= kSize) return;
  if (x + w > kSize) w = (int16_t)(kSize - x);
  if (y + h > kSize) h = (int16_t)(kSize - y);
  if (w <= 0 || h <= 0) return;
  openWindow(x, y, (int16_t)(x + w - 1), (int16_t)(y + h - 1));
  streamColor(color, (uint32_t)w * (uint32_t)h);
  closeWindow();
}

void Gc9a01::fillCircle(int16_t cx, int16_t cy, int16_t r, uint16_t color) {
  for (int16_t dy = -r; dy <= r; dy++) {
    int16_t dx = (int16_t)isqrt((uint32_t)((int32_t)r * r - (int32_t)dy * dy));
    fillRect((int16_t)(cx - dx), (int16_t)(cy + dy), (int16_t)(2 * dx + 1), 1, color);
  }
}

void Gc9a01::fillRing(int16_t cx, int16_t cy, int16_t rOuter, int16_t rInner, uint16_t color) {
  for (int16_t dy = -rOuter; dy <= rOuter; dy++) {
    int16_t dxo = (int16_t)isqrt((uint32_t)((int32_t)rOuter * rOuter - (int32_t)dy * dy));
    int16_t ady = (int16_t)(dy < 0 ? -dy : dy);
    if (ady <= rInner) {                                     // the hole is crossed on this row: two spans
      int16_t dxi = (int16_t)isqrt((uint32_t)((int32_t)rInner * rInner - (int32_t)dy * dy));
      fillRect((int16_t)(cx - dxo), (int16_t)(cy + dy), (int16_t)(dxo - dxi), 1, color);
      fillRect((int16_t)(cx + dxi + 1), (int16_t)(cy + dy), (int16_t)(dxo - dxi), 1, color);
    } else {
      fillRect((int16_t)(cx - dxo), (int16_t)(cy + dy), (int16_t)(2 * dxo + 1), 1, color);
    }
  }
}

void Gc9a01::drawChar(int16_t x, int16_t y, char c, uint8_t scale, uint16_t fg, uint16_t bg) {
  if (scale == 0) return;
  if (c < 32 || c > 126) c = '?';
  int16_t w = (int16_t)(6 * scale);
  int16_t h = (int16_t)(8 * scale);
  if (x < 0 || y < 0 || x + w > kSize || y + h > kSize) return;

  uint8_t col[5];
  const uint8_t* glyph = kFont + (uint16_t)(c - 32) * 5;
  for (uint8_t i = 0; i < 5; i++) col[i] = pgm_read_byte(glyph + i);

  uint8_t fh = (uint8_t)(fg >> 8), fl = (uint8_t)fg, bh = (uint8_t)(bg >> 8), bl = (uint8_t)bg;
  openWindow(x, y, (int16_t)(x + w - 1), (int16_t)(y + h - 1));
  for (uint8_t row = 0; row < 8; row++) {
    for (uint8_t ry = 0; ry < scale; ry++) {
      for (uint8_t cx = 0; cx < 6; cx++) {
        bool on = cx < 5 && row < 7 && ((col[cx] >> row) & 1);
        uint8_t hi = on ? fh : bh;
        uint8_t lo = on ? fl : bl;
        for (uint8_t rx = 0; rx < scale; rx++) {
          spiSend(hi);
          spiSend(lo);
        }
      }
    }
  }
  closeWindow();
}

void Gc9a01::drawText(int16_t x, int16_t y, const char* text, uint8_t scale, uint16_t fg, uint16_t bg) {
  for (; *text; text++) {
    drawChar(x, y, *text, scale, fg, bg);
    x = (int16_t)(x + 6 * scale);
  }
}

void Gc9a01::drawTextP(int16_t x, int16_t y, const __FlashStringHelper* text, uint8_t scale, uint16_t fg, uint16_t bg) {
  const char* p = reinterpret_cast<const char*>(text);
  for (char c; (c = (char)pgm_read_byte(p)) != 0; p++) {
    drawChar(x, y, c, scale, fg, bg);
    x = (int16_t)(x + 6 * scale);
  }
}
