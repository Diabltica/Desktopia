"""Builds Desktopia.3dshapes/WireLink_1.5sqmm_P6mm.wrl: the JP6 wire link of the motherboard (VM, 15 A), for the KiCad
3D view of KiCad's Connector_Wire:SolderWire-1.5sqmm_1x02_P6mm_D1.7mm_OD3mm footprint (same origin: pad 1, pad 2 at
x = 6 mm). KiCad ships no 3D model for that footprint.

A piece of red 1.5 mm2 wire (1.7 mm conductor, 3 mm insulation, as in the footprint's name) bent into a U over the
board: its stripped and tinned ends go through the two holes, are soldered on the bottom (a smaller fillet wicks up
to the top pad) and are cut about 1.5 mm under the board. Board thickness: 1.6 mm.

usage: python wire_link_3d.py [out.wrl]
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from vrml import Mesh, shape, write               # noqa: E402

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "Desktopia.3dshapes", "WireLink_1.5sqmm_P6mm.wrl")

PITCH = 6.0                     # pad 1 at x = 0, pad 2 at x = 6
PAD_R = 1.575                   # 3.15 mm pads
BOARD_T = 1.6
BOTTOM = -BOARD_T               # z of the board's bottom face
CU_T = 0.035

CORE_R, INS_R = 0.85, 1.5       # 1.7 mm conductor, 3 mm insulation
STRIP_TOP = 1.0                 # the insulation stops 1 mm above the top face
LEG_TOP = 2.0                   # straight legs up to here, then a half turn of radius PITCH / 2
CUT = BOTTOM - 1.5              # the ends are cut 1.5 mm under the board

# Materials: diffuse, specular, shininess, transparency, emissive
MAT = {
    "insulation": ((0.75, 0.06, 0.05), (0.3, 0.3, 0.3), 0.4, 0.0, None),    # red, like the 24 V nets of the schematic
    "tin": ((0.75, 0.75, 0.78), (0.9, 0.9, 0.9), 0.8, 0.0, None),
    "copper": ((0.72, 0.42, 0.20), (0.6, 0.45, 0.3), 0.6, 0.0, None),
}


def u_path(z_end, seg=32):
    """Axis of the wire: up leg 1, a half turn over the board, down leg 2."""
    r = PITCH / 2
    arc = [(r - r * math.cos(math.pi * k / seg), 0.0, LEG_TOP + r * math.sin(math.pi * k / seg)) for k in range(seg + 1)]
    return [(0.0, 0.0, z_end)] + arc + [(PITCH, 0.0, z_end)]


def fillet(mesh, x, z_pad, height, r_pad, n=8):
    """Concave solder fillet around the wire at (x, 0): from r_pad on the pad (z_pad) to the wire, height mm away
    from the board (negative: under it). Profile listed by increasing z, as Mesh.revolve expects."""
    prof = [(r_pad - (r_pad - CORE_R) * math.sin(math.pi / 2 * k / n), z_pad + height * (1 - math.cos(math.pi / 2 * k / n)))
            for k in range(n + 1)]
    mesh.revolve(x, 0.0, prof if height > 0 else list(reversed(prof)))


def build():
    parts = []

    insulation = Mesh()
    insulation.tube(u_path(STRIP_TOP), INS_R, seg=24)
    parts.append(shape("insulation", insulation, MAT["insulation"]))

    tin, copper = Mesh(), Mesh()
    for x in (0.0, PITCH):
        tin.tube([(x, 0.0, CUT), (x, 0.0, STRIP_TOP + 0.1)], CORE_R, seg=16, caps=False)
        copper.poly([(x + CORE_R * math.cos(-2 * math.pi * k / 16), CORE_R * math.sin(-2 * math.pi * k / 16), CUT)
                     for k in range(16)])                                   # the cut end, facing down
        fillet(tin, x, CU_T, 0.6, PAD_R - 0.1)                              # wicked up to the top pad
        fillet(tin, x, BOTTOM - CU_T, -1.0, PAD_R - 0.05)                   # soldered on the bottom
    parts += [shape("tin", tin, MAT["tin"]), shape("copper", copper, MAT["copper"])]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    write(OUT, "1.5 mm2 wire link soldered in JP6 of the motherboard - generated by "
               "hardware/kicad_library/pcb/tools/wire_link_3d.py", parts)
    print("%s: %d shapes, %.0f kB" % (OUT, len(parts), os.path.getsize(OUT) / 1024))


build()
